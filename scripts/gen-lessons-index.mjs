// src/content/cp3p/<level>/*.json dan src/content/cp3p/index.ts ni yaratadi (statik importlar, tartib bo'yicha).
// Usage: node scripts/gen-lessons-index.mjs   (dars qo'shilganda/o'chirilganda qayta ishga tushiring)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const base = path.join(root, "src/content/cp3p");
const levels = ["foundation", "preparation", "execution"];
const lines = ["// AUTO-GENERATED by scripts/gen-lessons-index.mjs — do not edit.", 'import type { Lesson } from "./types";'];
const lists = {};
let n = 0;
for (const lvl of levels) {
  const dir = path.join(base, lvl);
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".json")) : [];
  const items = files
    .map((f) => ({ f, order: JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")).order }))
    .sort((a, b) => a.order - b.order);
  lists[lvl] = items.map(({ f }) => {
    const name = `L${n++}`;
    lines.push(`import ${name} from "./${lvl}/${f}";`);
    return name;
  });
}
lines.push("", "export const LESSONS: Record<\"foundation\" | \"preparation\" | \"execution\", Lesson[]> = {");
for (const lvl of levels) lines.push(`  ${lvl}: [${lists[lvl].join(", ")}] as Lesson[],`);
lines.push("};", "");
const target = path.join(base, "index.ts");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== lines.join("\n")) {
    console.error("src/content/cp3p/index.ts is stale — run: node scripts/gen-lessons-index.mjs");
    process.exit(1);
  }
} else fs.writeFileSync(target, lines.join("\n"));
console.log(levels.map((l) => `${l} ${lists[l].length}`).join(", "));
